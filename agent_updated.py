def process_user_query_with_agents_sdk(query: str) -> str:
    """Process user query using the OpenAI Agents SDK and return formatted response"""
    try:
        # Create the agent
        agent = create_agent_with_tools()

        # Run the agent with the query
        result = Runner.run_sync(agent, query)

        # Return the agent's response
        return result.final_output

    except Exception as e:
        logger.error(f"Error processing user query with Agents SDK: {e}")
        return "Sorry, I encountered an error while processing your request. Please try again."


def run_conversation_loop():
    """Create conversation loop with context management for the agent using Agents SDK"""
    print("🚀 Starting AI Agent with Retrieval-Augmented Capabilities (Agents SDK)")
    print("You can ask questions about the Physical AI & Humanoid Robotics book content.")
    print("Type 'quit', 'exit', or 'q' to stop the conversation.\n")

    # Initialize the agent
    try:
        agent = create_agent_with_tools()
        print("✅ Agent initialized with retrieval tools\n")
    except Exception as e:
        print(f"❌ Error initializing agent: {e}")
        print("Please check your environment variables and API keys.")
        return

    # Conversation loop
    while True:
        try:
            user_input = input("\n💬 You: ").strip()

            if user_input.lower() in ['quit', 'exit', 'q']:
                print(f"\n👋 Goodbye!")
                break

            if not user_input:
                continue

            # Process the user input with the agent using the Agents SDK
            result = Runner.run_sync(agent, user_input)
            response = result.final_output
            print(f"🤖 Agent: {response}")

        except KeyboardInterrupt:
            print(f"\n\n👋 Goodbye!")
            break
        except Exception as e:
            print(f"\n❌ Error processing query: {e}")
            continue


